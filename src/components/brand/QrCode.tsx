import { useEffect, useState } from 'react'
import QRCode from 'qrcode'

import { cn } from '@/lib/utils'

/** QR code as crisp SVG in the brand burgundy (prints sharp at any size). */
export function QrCode({ value, className }: { value: string; className?: string }) {
  const [svg, setSvg] = useState('')

  useEffect(() => {
    let alive = true
    QRCode.toString(value, { type: 'svg', margin: 1, errorCorrectionLevel: 'M', color: { dark: '#720f22', light: '#ffffff' } })
      .then((s) => alive && setSvg(s))
      .catch(console.error)
    return () => {
      alive = false
    }
  }, [value])

  return (
    <div
      role="img"
      aria-label={`QR: ${value}`}
      className={cn('aspect-square [&>svg]:size-full', className)}
      // generated by the qrcode library from our own URL, not user input
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}
